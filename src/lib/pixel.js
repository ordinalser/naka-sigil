  function digitsPath(text) {
    let x = 0, d = '';
    for (const c of text) {
      const rows = DIGITS[c];
      if (!rows) throw new Error('Unsupported pixel digit');
      rows.forEach((row,y) => [...row].forEach((bit,dx) => { if (bit==='1') d += `M${x+dx} ${y}h1v1h-1z`; }));
      x += rows[0].length + 1;
    }
    return { d, width:Math.max(0,x-1) };
  }
