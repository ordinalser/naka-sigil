/** Portable demo, generated from the same audited runtime; no separate formula implementation. */
'use strict';
const fs=require('node:fs'),path=require('node:path');
const ROOT=path.join(__dirname,'..');
function render(){
 const base=path.join(ROOT,'demo');let html=fs.readFileSync(path.join(base,'index.html'),'utf8');
 const read=rel=>{const file=path.resolve(base,rel);if(!file.startsWith(path.join(ROOT,'src')+path.sep))throw Error('Unexpected demo dependency');return fs.readFileSync(file,'utf8');};
 html=html.replace(/<link rel="stylesheet" href="([^"]+)">/g,(_,rel)=>`<style>\n${read(rel)}\n</style>`);
 html=html.replace(/<script src="([^"]+)"><\/script>/g,(_,rel)=>{const code=read(rel);if(/<\/script/i.test(code))throw Error('Unsafe embedded script terminator');return `<script>\n${code}\n</script>`;});
 return '<!-- Generated by scripts/package-demo.js from the shared runtime. -->\n'+html;
}
if(require.main===module){fs.writeFileSync(path.join(ROOT,'demo/naka-sigil-demo.html'),render());console.log('Prepared portable demo: demo/naka-sigil-demo.html');}
module.exports={render};
